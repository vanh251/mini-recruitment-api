CREATE TABLE companies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(200) NOT NULL CHECK (length(trim(name)) > 0),
    address VARCHAR(500) NOT NULL CHECK (length(trim(address)) > 0),
    website VARCHAR(2048) NOT NULL CHECK (website ~* '^https?://[^[:space:]]+$')
);

CREATE TABLE jobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES companies(id) ON DELETE RESTRICT,
    title VARCHAR(200) NOT NULL CHECK (length(trim(title)) > 0),
    description TEXT NOT NULL CHECK (length(trim(description)) > 0 AND length(description) <= 10000),
    salary_from NUMERIC(15, 2) NOT NULL CHECK (salary_from >= 0),
    salary_to NUMERIC(15, 2) NOT NULL,
    location VARCHAR(200) NOT NULL CHECK (length(trim(location)) > 0),
    status VARCHAR(6) NOT NULL CHECK (status IN ('OPEN', 'CLOSED')),
    CONSTRAINT ck_job_salary_range CHECK (salary_to >= salary_from)
);
CREATE INDEX idx_jobs_company ON jobs(company_id);
CREATE INDEX idx_jobs_status_location ON jobs(status, location);

CREATE TABLE applications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id BIGINT NOT NULL REFERENCES jobs(id) ON DELETE RESTRICT,
    full_name VARCHAR(200) NOT NULL CHECK (length(trim(full_name)) > 0),
    email VARCHAR(254) NOT NULL CHECK (length(email) > 0 AND email = lower(trim(email))),
    cv_url VARCHAR(2048) NOT NULL CHECK (cv_url ~* '^https?://[^[:space:]]+$'),
    applied_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_applications_job_email UNIQUE (job_id, email)
);
